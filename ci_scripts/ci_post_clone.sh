#!/bin/sh
# Xcode Cloud runs this after cloning. Secrets.swift is gitignored, so write it
# from the workflow's secret environment variables (Manage Workflows →
# Environment → Environment Variables, each marked Secret).
set -e

missing=""
for name in PERPLEXITY_API_KEY CARAPI_TOKEN CARAPI_SECRET; do
  eval "value=\${$name}"
  [ -z "$value" ] && missing="$missing $name"
done
if [ -n "$missing" ]; then
  echo "error: missing Xcode Cloud environment variables:$missing" >&2
  exit 1
fi

cat > "$CI_PRIMARY_REPOSITORY_PATH/claude automate/Services/Secrets.swift" <<SWIFT
import Foundation

/// Generated by ci_scripts/ci_post_clone.sh in Xcode Cloud. Not committed.
enum Secrets {
    static let perplexityAPIKey = "$PERPLEXITY_API_KEY"
    static let carAPIToken = "$CARAPI_TOKEN"
    static let carAPISecret = "$CARAPI_SECRET"
}
SWIFT
echo "Wrote Secrets.swift"
